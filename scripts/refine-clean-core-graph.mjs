#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const base = new URL('../skills/sap-erp-clean-core-refactor/knowledge/clean-core-extensibility/graphify-out/', import.meta.url);
const sourceFile = fileURLToPath(new URL('graph.json', base));
const targetFile = fileURLToPath(new URL('graph.curated.json', base));
const reportFile = fileURLToPath(new URL('CURATION.md', base));

const explicitAliases = new Map([
  ['extension_points', 'released_sap_extension_point'],
  ['joule_for_developers_abap', 'sap_joule_for_developers_abap_ai'],
]);

const curatedLinks = [
  ['sap_discovery_center_missions', 'side_by_side_extensibility', 'supports'],
  ['abap_restful_application_programming_model', 'developer_extensibility', 'implements'],
  ['sap_cloud_erp_private_advisory', 'clean_core_extensibility_governance', 'supports'],
];

function normalizedLabel(node) {
  return (node.norm_label ?? node.label ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '');
}

function degreeById(graph) {
  const degree = new Map(graph.nodes.map((node) => [node.id, 0]));
  for (const link of graph.links) {
    degree.set(link.source, (degree.get(link.source) ?? 0) + 1);
    degree.set(link.target, (degree.get(link.target) ?? 0) + 1);
  }
  for (const hyperedge of graph.hyperedges ?? []) {
    for (const id of hyperedge.nodes ?? []) degree.set(id, (degree.get(id) ?? 0) + 1);
  }
  return degree;
}

export function refineGraph(source) {
  const graph = structuredClone(source);
  const canonicalById = new Map(graph.nodes.map((node) => [node.id, node.id]));
  const groups = new Map();
  for (const node of graph.nodes) {
    const key = normalizedLabel(node);
    const group = groups.get(key) ?? [];
    group.push(node.id);
    groups.set(key, group);
  }
  for (const ids of groups.values()) {
    if (ids.length < 2) continue;
    for (const alias of ids.slice(1)) canonicalById.set(alias, ids[0]);
  }
  for (const [alias, canonical] of explicitAliases) canonicalById.set(alias, canonical);

  const aliasesByCanonical = new Map();
  for (const [id, canonical] of canonicalById) {
    if (id === canonical) continue;
    const aliases = aliasesByCanonical.get(canonical) ?? [];
    aliases.push(id);
    aliasesByCanonical.set(canonical, aliases);
  }

  graph.nodes = graph.nodes
    .filter((node) => canonicalById.get(node.id) === node.id)
    .map((node) => ({ ...node, alias_ids: (aliasesByCanonical.get(node.id) ?? []).sort() }));

  const linkKeys = new Set();
  graph.links = graph.links.flatMap((link) => {
    const sourceId = canonicalById.get(link.source) ?? link.source;
    const targetId = canonicalById.get(link.target) ?? link.target;
    if (sourceId === targetId) return [];
    const key = `${sourceId}|${targetId}|${link.relation}`;
    if (linkKeys.has(key)) return [];
    linkKeys.add(key);
    return [{ ...link, source: sourceId, target: targetId }];
  });

  graph.hyperedges = (graph.hyperedges ?? []).map((hyperedge) => ({
    ...hyperedge,
    nodes: [...new Set((hyperedge.nodes ?? []).map((id) => canonicalById.get(id) ?? id))],
  }));

  const nodeIds = new Set(graph.nodes.map((node) => node.id));
  for (const [sourceId, targetId, relation] of curatedLinks) {
    if (!nodeIds.has(sourceId) || !nodeIds.has(targetId)) continue;
    const key = `${sourceId}|${targetId}|${relation}`;
    if (linkKeys.has(key)) continue;
    graph.links.push({
      source: sourceId,
      target: targetId,
      relation,
      confidence: 'CURATED',
      confidence_score: 1,
      source_file: 'graphify-out/CURATION.md',
      source_location: 'Curated semantic bridge v1',
      weight: 1,
    });
    linkKeys.add(key);
  }

  graph.graph = { ...graph.graph, curation_version: 1, source_graph: 'graph.json' };
  return graph;
}

function run() {
  const source = JSON.parse(readFileSync(sourceFile, 'utf8'));
  const beforeDegree = degreeById(source);
  const beforeIsolates = source.nodes.filter((node) => (beforeDegree.get(node.id) ?? 0) === 0).map((node) => node.id);
  const curated = refineGraph(source);
  const afterDegree = degreeById(curated);
  const afterIsolates = curated.nodes.filter((node) => (afterDegree.get(node.id) ?? 0) === 0).map((node) => node.id);
  const aliasCount = curated.nodes.reduce((total, node) => total + (node.alias_ids?.length ?? 0), 0);

  writeFileSync(targetFile, `${JSON.stringify(curated, null, 2)}\n`);
  writeFileSync(
    reportFile,
    `# Clean Core Graph Curation\n\n` +
      `The original \`graph.json\` remains the immutable Graphify extraction. ` +
      `\`graph.curated.json\` is a deterministic runtime/exploration refinement generated by ` +
      `\`npm run clean-core:graph\`.\n\n` +
      `| Metric | Source | Curated |\n|---|---:|---:|\n` +
      `| Nodes | ${source.nodes.length} | ${curated.nodes.length} |\n` +
      `| Links | ${source.links.length} | ${curated.links.length} |\n` +
      `| Zero-degree nodes | ${beforeIsolates.length} | ${afterIsolates.length} |\n` +
      `| Merged alias IDs | 0 | ${aliasCount} |\n\n` +
      `## Curated bridges\n\n` +
      curatedLinks.map(([from, to, relation]) => `- \`${from}\` -[${relation}]-> \`${to}\``).join('\n') +
      `\n\nThese bridges connect previously zero-degree high-level concepts. They are marked ` +
      `\`confidence=CURATED\` and never authorize execution. Runtime decisions use ` +
      `\`decision-rules.json\` plus live evidence. Graphify's original report also labels 94 nodes ` +
      `as weakly connected; they remain an exploration-quality signal rather than an execution gap.\n`,
  );
  console.log(`Curated graph written: ${curated.nodes.length} nodes, ${curated.links.length} links, ${afterIsolates.length} isolates.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) run();
